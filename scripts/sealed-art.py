#!/usr/bin/env python3
"""Turns the owner's sealed product photos into our own files, and rebuilds both lists.

Put one folder per set in art-inbox/ (folder = set name, file = product name), then run:
    python3 scripts/sealed-art.py
Each picture is cleaned (white backgrounds cut out, edges trimmed, at most 800px), saved as
public/products/pokemon/<set>/<product>.webp, and listed in src/lib/sealed-art-manifest.json and
ios/Holo/Domain/SealedArtList.swift (the same list, generated, so the two never drift).
Sets already in the manifest keep their entries; a folder adds to or replaces its set's files.
"""
import json, os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
INBOX = os.path.join(ROOT, "art-inbox")
PUBLIC = os.path.join(ROOT, "public", "products")
MANIFEST = os.path.join(ROOT, "src", "lib", "sealed-art-manifest.json")
SWIFT = os.path.join(ROOT, "ios", "Holo", "Domain", "SealedArtList.swift")

# Folder name → the set as the catalog names it, and other names it goes by.
SETS = {
    "SV - 151": ("151", ["Scarlet & Violet 151"]),
    "Scarlet & Violet Base Set": ("Scarlet & Violet Base Set", ["Scarlet & Violet"]),
    "Pokemon Go": ("Pokemon GO", []),
    "Prismatic Evolutions": ("Prismatic Evolutions", ["Prismatic Evolution"]),
    "Celebrations": ("Celebrations", ["25th Anniversary Celebrations"]),
}

def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower().replace("&", "and").replace("é", "e")).strip("-")

def clean_label(base):
    base = re.sub(r'\s*",.*$', "", base)          # leftover web addresses: ` ","image_url"-"https…`
    base = re.sub(r"^Pokemon-\s*", "", base)
    return re.sub(r"\s+", " ", base).strip()

def opaque_corner(path):
    out = subprocess.check_output(["convert", path, "-alpha", "on", "-format", "%[fx:p{0,0}.a] %[fx:p{0,0}.r]", "info:"]).decode().split()
    return float(out[0]) > 0.9 and float(out[1]) > 0.9   # an opaque, near-white corner

def convert(src, dst):
    cmd = ["convert", src, "-alpha", "set"]
    if opaque_corner(src):
        w, h = map(int, subprocess.check_output(["identify", "-format", "%w %h", src + "[0]"]).split())
        cmd += ["-fuzz", "4%", "-fill", "none"]
        for x, y in [(0, 0), (w - 1, 0), (0, h - 1), (w - 1, h - 1)]:
            cmd += ["-draw", f"color {x},{y} floodfill"]
    cmd += ["-trim", "+repage", "-resize", "800x800>", "-quality", "86", "-define", "webp:alpha-quality=90", dst]
    subprocess.check_call(cmd)

def main():
    manifest = json.load(open(MANIFEST)) if os.path.exists(MANIFEST) else {"sets": []}
    by_set = {e["set"]: e for e in manifest["sets"]}
    for folder in sorted(os.listdir(INBOX)):
        path = os.path.join(INBOX, folder)
        if not os.path.isdir(path):
            continue
        set_name, aliases = SETS.get(folder, (folder, []))
        d = f"pokemon/{slug(set_name)}"
        os.makedirs(os.path.join(PUBLIC, d), exist_ok=True)
        entry = by_set.setdefault(set_name, {"set": set_name, "dir": d, "products": {}})
        if aliases:
            entry["aliases"] = aliases
        for f in sorted(os.listdir(path)):
            if f.startswith(".") or not re.search(r"\.(png|jpe?g|webp)$", f, re.I):
                continue
            label = clean_label(os.path.splitext(f)[0])
            name = slug(label)
            convert(os.path.join(path, f), os.path.join(PUBLIC, d, name + ".webp"))
            entry["products"][label] = name
        print(f"{set_name}: {len(entry['products'])}")
    manifest["sets"] = sorted(by_set.values(), key=lambda e: e["set"])
    json.dump(manifest, open(MANIFEST, "w"), indent=2, ensure_ascii=False)
    open(MANIFEST, "a").write("\n")
    lines = ["// Generated by scripts/sealed-art.py from src/lib/sealed-art-manifest.json. Don't edit by hand.", "", "extension SealedArt {", "    static let entries: [Entry] = ["]
    q = lambda s: json.dumps(s, ensure_ascii=False)
    for e in manifest["sets"]:
        lines.append(f"        Entry(set: {q(e['set'])}, aliases: [{', '.join(q(a) for a in e.get('aliases', []))}], dir: {q(e['dir'])}, products: [")
        for k, v in sorted(e["products"].items()):
            lines.append(f"            {q(k)}: {q(v)},")
        lines.append("        ]),")
    lines += ["    ]", "}", ""]
    open(SWIFT, "w").write("\n".join(lines))

if __name__ == "__main__":
    sys.exit(main())
